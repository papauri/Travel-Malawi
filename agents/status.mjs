#!/usr/bin/env node
// Tracker: zero-token status of every department lead, read from agents/board.
// Usage: node agents/status.mjs [--write]   (--write also saves agents/board/TRACKER.md)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const board = path.join(root, 'board');
const LEADS = ['platform', 'booking', 'property', 'onboarding', 'ai', 'messaging', 'settings', 'ui', 'ux', 'cleanup'];

const read = (p) => (fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : '');

const rows = LEADS.map((lead) => {
  const log = read(path.join(board, `${lead}.md`));
  const inbox = read(path.join(board, 'inbox', `${lead}.md`));
  const statuses = [...log.matchAll(/^status:\s*(\S+)/gim)].map((m) => m[1].toLowerCase());
  const status = !log ? 'not-started' : statuses.at(-1) || 'in-progress';
  const count = (re) => (log.match(re) || []).length;
  const handoffIds = [...inbox.matchAll(/\[(H-[\w-]+)\]/g)].map((m) => m[1]);
  const dupes = handoffIds.filter((id, i) => handoffIds.indexOf(id) !== i);
  if (dupes.length) console.error(`WARN ${lead} inbox has duplicate handoff ids: ${[...new Set(dupes)].join(' ')}`);
  const pending = handoffIds.filter((id) => !new RegExp(`\\[${id}\\]\\s+(DONE|REJECTED)`).test(log));
  return { lead, status, fixed: count(/\bFIXED\b/g), logged: count(/\bLOGGED\b/g), pending };
});

const notDone = rows.filter((r) => r.lead !== 'cleanup' && r.status !== 'done');
const inboxWork = rows.filter((r) => r.lead !== 'cleanup' && r.status === 'done' && r.pending.length);
const cleanup = rows.find((r) => r.lead === 'cleanup');
const next = notDone.length
  ? `Wave 1 (resume): ${notDone.map((r) => r.lead).join(', ')}`
  : inboxWork.length
    ? `Wave 2 (inbox): ${inboxWork.map((r) => r.lead).join(', ')}`
    : cleanup.status !== 'done'
      ? 'Wave 3: cleanup'
      : 'Verify: npm run lint && npm run build && npm run check:validation, then commit + push';

const lines = [
  '# Tracker — generated by `node agents/status.mjs --write` (do not edit by hand)',
  '',
  '| Lead | Status | Fixed | Logged | Pending handoffs |',
  '|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.lead} | ${r.status} | ${r.fixed} | ${r.logged} | ${r.pending.join(' ') || '-'} |`),
  '',
  `**Next:** ${next}`,
  '',
];
const out = lines.join('\n');
process.stdout.write(out);
if (process.argv.includes('--write')) {
  fs.mkdirSync(board, { recursive: true });
  fs.writeFileSync(path.join(board, 'TRACKER.md'), out);
}
